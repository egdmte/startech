def current_language() -> str:
    """Return the selected interface language, defaulting to English."""

    selected = session.get("language")
    return str(selected) if selected in SUPPORTED_LANGUAGES else "en"


def translate(text: str, **values: Any) -> str:
    """Translate one source string and interpolate named values."""

    rendered = TURKISH.get(text, text) if current_language() == "tr" else text
    return rendered.format(**values) if values else rendered


